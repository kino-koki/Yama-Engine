# 运行: python research/tokenizer-free/tests/test_tokenizer_free.py

import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from entropy_patcher import ByteEntropyModel, patch_bytes, unpatch  # noqa: E402
from patch_lm import build_training_data, train_demo  # noqa: E402

_results = []


def check(name, fn):
    try:
        fn()
        _results.append((name, True, ""))
        print(f"  [PASS] {name}")
    except AssertionError as e:
        _results.append((name, False, str(e)))
        print(f"  [FAIL] {name}: {e}")
    except Exception as e:  # noqa: BLE001
        _results.append((name, False, f"{type(e).__name__}: {e}"))
        print(f"  [FAIL] {name}: {type(e).__name__}: {e}")


def expect(cond, msg):
    if not cond:
        raise AssertionError(msg)


# ── 1. patch 无损往返 ──
def test_roundtrip():
    random.seed(7)
    for data in (
        b"",
        b"a",
        b"hello world, hello patches!",
        "分词器不是必需品：模型可以直接理解字节。".encode("utf-8"),
        bytes(random.randrange(256) for _ in range(500)),
    ):
        patches = patch_bytes(data)
        expect(unpatch(patches) == data, f"round-trip failed for {data[:24]!r}...")


# ── 2. 熵自适应: 随机数据 patch 数 > 重复数据 (同长度) ──
def test_entropy_adaptive_patching():
    random.seed(42)
    rand_data = bytes(random.randrange(256) for _ in range(600))
    rep_data = b"abcabcabc" * 67  # 603 字节, 高度可预测
    model = ByteEntropyModel(order=4)
    model.train(rand_data + rep_data)
    rand_patches = patch_bytes(rand_data, model)
    rep_patches = patch_bytes(rep_data, model)
    expect(len(rand_patches) > len(rep_patches),
           f"random ({len(rand_patches)}) should need more patches than repetitive ({len(rep_patches)})")
    expect(max(len(p) for p in rep_patches) > 8,
           "repetitive data should form long patches")


# ── 3. 信息量突增处切分: 长 run 后接新字节, 边界应落在新内容前 ──
def test_boundary_at_information_jump():
    data = b"a" * 40 + b"b" + b"a" * 40
    model = ByteEntropyModel(order=2)
    model.train(data)
    patches = patch_bytes(data, model, threshold=2.0, min_patch=2, max_patch=64)
    expect(unpatch(patches) == data, "round-trip must hold")
    expect(len(patches) >= 2, f"expected a split at the 'b' jump, got {len(patches)} patch(es)")
    joined = b"|".join(patches)
    expect(b"a|b" in joined or b"|b" in joined or any(p == b"b" or p.startswith(b"b") for p in patches),
            "a patch boundary should isolate the surprising byte 'b'")


# ── 4. 多语言 UTF-8 (中英混排 + 代码) 无损 ──
def test_utf8_multilingual_roundtrip():
    data = ("def f(x):  # 注释\n"
            "    return x * 2  # 乘法\n"
            "模型直接读字节，跳过分词器。Emoji: 🚀\n").encode("utf-8")
    model = ByteEntropyModel(order=4)
    model.train(data)
    patches = patch_bytes(data, model)
    expect(unpatch(patches) == data, "multilingual utf-8 round-trip failed")


# ── 5. patch LM: 训练降损 + 生成可解码 ──
def test_patch_lm_train_and_generate():
    model, vocab, first_loss, final_loss, seq = train_demo(steps=200, lr=0.05, seed=0)
    expect(len(vocab) > 10, f"vocab too small: {len(vocab)}")
    expect(final_loss < first_loss,
           f"training should reduce loss ({first_loss:.3f} -> {final_loss:.3f})")
    gen_ids = model.generate(seq[:16], max_new=24, temperature=0.7)
    expect(len(gen_ids) == 16 + 24, "generate should extend by max_new")
    data = vocab.decode(gen_ids)
    expect(isinstance(data, bytes), "decoded generation must be bytes")
    # 重新编码解码闭合 (生成 id 均在词表内)
    re_ids = vocab.encode(patch_bytes(data))
    expect(vocab.decode(re_ids) == data, "re-encoding generated bytes must round-trip")


if __name__ == "__main__":
    check("RoundTrip", test_roundtrip)
    check("EntropyAdaptivePatching", test_entropy_adaptive_patching)
    check("BoundaryAtInformationJump", test_boundary_at_information_jump)
    check("Utf8MultilingualRoundtrip", test_utf8_multilingual_roundtrip)
    check("PatchLMTrainAndGenerate", test_patch_lm_train_and_generate)
    failed = [r for r in _results if not r[1]]
    print(f"== tokenizer-free: {len(_results) - len(failed)}/{len(_results)} passed ==")
    sys.exit(1 if failed else 0)
