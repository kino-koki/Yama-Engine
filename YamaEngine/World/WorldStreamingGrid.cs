    /// <summary>
    /// 数据层。对标 UE5/UE6 Data Layer，实现世界数据的逻辑分层，
    /// 允许按层独立加载/卸载/设置可见性。用于大规模开放世界的分层构建。
    /// </summary>
    public sealed class DataLayer
    {
        /// <summary>层 ID。</summary>
        public Guid Id { get; } = Guid.NewGuid();

        /// <summary>层名称。</summary>
        public string Name { get; set; }

        /// <summary>层加载策略。</summary>
        public DataLayerLoadingStrategy Strategy { get; set; } = DataLayerLoadingStrategy.AlwaysLoaded;

        /// <summary>是否当前已加载。</summary>
        public bool IsLoaded { get; set; }

        /// <summary>是否当前可见（加载但不可见时仍占用内存但不参与渲染）。</summary>
        public bool IsVisible { get; set; } = true;

        /// <summary>加载优先级权重（0~1，影响该层内 Cell 的优先级加成）。</summary>
        public float PriorityWeight { get; set; } = 1f;

        /// <summary>距离策略：加载半径（世界单位）。</summary>
        public float LoadRadius { get; set; } = 512f;

        /// <summary>距离策略：卸载半径（大于此距离卸载）。</summary>
        public float UnloadRadius { get; set; } = 768f;

        /// <summary>所属层组名称（用于批量操作）。</summary>
        public string LayerGroup { get; set; } = "Default";

        /// <summary>该层包含的所有 Cell ID。</summary>
        public readonly HashSet<Guid> CellIds = new();

        /// <summary>该层内关联的流送体积 ID。</summary>
        public readonly HashSet<Guid> VolumeIds = new();

        /// <summary>内存占用（KB）。</summary>
        public long MemoryFootprintKB;

        /// <summary>数据层状态变更事件。</summary>
        public event Action<DataLayer, bool>? OnLoadStateChanged;

        public DataLayer(string name)
        {
            Name = name;
        }

        /// <summary>设置加载状态并触发事件。</summary>
        public void SetLoaded(bool loaded)
        {
            if (IsLoaded == loaded) return;
            IsLoaded = loaded;
            OnLoadStateChanged?.Invoke(this, loaded);
        }

        /// <summary>添加 Cell 到此数据层。</summary>
        public void AddCell(Guid cellId)
        {
            CellIds.Add(cellId);
        }

        /// <summary>从数据层移除 Cell。</summary>
        public void RemoveCell(Guid cellId)
        {
            CellIds.Remove(cellId);
        }
    }

