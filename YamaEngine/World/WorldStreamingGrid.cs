            int y = (int)MathF.Floor(worldPos.Y / _options.CellSize);
            int z = (int)MathF.Floor(worldPos.Z / _options.CellSize);
            _gridLookup.TryGetValue((x, y, z), out var cell);
            return cell;
        }

