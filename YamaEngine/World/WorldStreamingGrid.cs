        public List<WorldCell> GetCellsInFrustum(Matrix4x4 viewProj)
        {
            var result = new List<WorldCell>();
            Span<Vector4> planes = stackalloc Vector4[6];
            ExtractFrustumPlanes(viewProj, planes);

            foreach (var cell in _activeCells)
            {
                if (IntersectsFrustum(cell.Bounds, planes))
                    result.Add(cell);
            }
            return result;
        }

        private static void ExtractFrustumPlanes(Matrix4x4 m, Span<Vector4> planes)
        {
            planes[0] = new Vector4(m.M11 + m.M14, m.M21 + m.M24, m.M31 + m.M34, m.M41 + m.M44); // left
            planes[1] = new Vector4(m.M14 - m.M11, m.M24 - m.M21, m.M34 - m.M31, m.M44 - m.M41); // right
            planes[2] = new Vector4(m.M12 + m.M14, m.M22 + m.M24, m.M32 + m.M34, m.M42 + m.M44); // bottom
            planes[3] = new Vector4(m.M14 - m.M12, m.M24 - m.M22, m.M34 - m.M32, m.M44 - m.M42); // top
            planes[4] = new Vector4(m.M13 + m.M14, m.M23 + m.M24, m.M33 + m.M34, m.M43 + m.M44); // near
            planes[5] = new Vector4(m.M14 - m.M13, m.M24 - m.M23, m.M34 - m.M33, m.M44 - m.M43); // far
        }

        private static bool IntersectsFrustum(BoundingBox box, Span<Vector4> planes)
        {
            for (int i = 0; i < 6; i++)
            {
                var p = planes[i];
                Vector3 pv = new(
                    p.X >= 0f ? box.Max.X : box.Min.X,
                    p.Y >= 0f ? box.Max.Y : box.Min.Y,
                    p.Z >= 0f ? box.Max.Z : box.Min.Z);
                float dist = p.X * pv.X + p.Y * pv.Y + p.Z * pv.Z + p.W;
                if (dist < 0f) return false;
            }
            return true;
        }

