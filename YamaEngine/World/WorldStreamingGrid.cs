    /// <summary>
    /// 分区异步加载请求。实现了 IComparable 接口以支持优先级排序。
    /// </summary>
    internal sealed class PartitionLoadRequest : IComparable<PartitionLoadRequest>
    {
        /// <summary>目标 Cell ID。</summary>
        public Guid CellId;

        /// <summary>优先级得分（越高越优先）。</summary>
        public float Priority;

        /// <summary>请求时间。</summary>
        public DateTime RequestTime;

        /// <summary>是否为卸载请求。</summary>
        public bool IsUnload;

        /// <summary>目标 LOD 等级。</summary>
        public int TargetLod;

        public int CompareTo(PartitionLoadRequest? other)
        {
            if (other == null) return 1;
            // 卸载请求优先级低于加载请求
            if (IsUnload != other.IsUnload)
                return IsUnload ? 1 : -1;
            int cmp = other.Priority.CompareTo(Priority);
            if (cmp != 0) return cmp;
            return RequestTime.CompareTo(other.RequestTime);
        }
    }

