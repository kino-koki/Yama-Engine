                (int)MathF.Floor(worldPos.Z / _options.CellSize)
            );
        }

        /// <summary>
        /// 获取指定半径内所有 Cell。
        /// </summary>
        public List<WorldCell> GetCellsInRadius(Vector3 center, int radiusInCells)
        {
            var result = new List<WorldCell>();
            int cx = (int)MathF.Floor(center.X / _options.CellSize);
            int cy = (int)MathF.Floor(center.Y / _options.CellSize);
            int cz = (int)MathF.Floor(center.Z / _options.CellSize);
            for (int x = cx - radiusInCells; x <= cx + radiusInCells; x++)
                for (int y = cy - radiusInCells; y <= cy + radiusInCells; y++)
                    for (int z = cz - radiusInCells; z <= cz + radiusInCells; z++)
                        if (_gridLookup.TryGetValue((x, y, z), out var cell))
                            result.Add(cell);
            return result;
        }

