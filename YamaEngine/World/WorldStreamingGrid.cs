        /// <summary>创建 HLOD 集群。</summary>
        public HlodCluster CreateHlodCluster(List<Guid> sourceCellIds, float switchDistance,
            HlodSourceMode mode = HlodSourceMode.AutoGenerated)
        {
            var cluster = new HlodCluster
            {
                SwitchDistance = switchDistance,
                SourceMode = mode
            };
            foreach (var cellId in sourceCellIds)
            {
                cluster.SourceCellIds.Add(cellId);
                // 关联 Cell 到 HLOD
                if (_cells.TryGetValue(cellId, out var cell))
                {
                    cell.HlodAssetId = cluster.Id;
                    cell.HlodSwitchDistance = switchDistance;
                }
                _cellHlodMapping[cellId] = cluster.Id;
            }

            // 计算集群边界
            if (sourceCellIds.Count > 0)
            {
                Vector3 min = Vector3.One * float.MaxValue;
                Vector3 max = Vector3.One * float.MinValue;
                foreach (var cellId in sourceCellIds)
                {
                    if (_cells.TryGetValue(cellId, out var cell))
                    {
                        min = Vector3.Min(min, cell.Bounds.Min);
                        max = Vector3.Max(max, cell.Bounds.Max);
                    }
                }
                cluster.Bounds = new BoundingBox(min, max);
            }

            _hlodClusters[cluster.Id] = cluster;
            Log($"创建 HLOD 集群: {sourceCellIds.Count} 个 Cell, 切换距离={switchDistance}");
            return cluster;
        }

        /// <summary>获取 Cell 关联的 HLOD 集群。</summary>
        public HlodCluster? GetHlodClusterForCell(Guid cellId) =>
            _cellHlodMapping.TryGetValue(cellId, out var clusterId) &&
            _hlodClusters.TryGetValue(clusterId, out var cluster) ? cluster : null;

