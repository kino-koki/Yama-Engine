        // ══════════════════════════════════════════════════════════════════════
        // 主更新循环（重写，UE6 级完整实现）
        // ══════════════════════════════════════════════════════════════════════

        /// <summary>
        /// 每帧更新。执行完整的分区流送流程。
        /// </summary>
        public void Update(float dt, Vector3 viewpoint)
        {
            _viewpoint = viewpoint;

            // 计算视点速度（用于预测加载）
            _viewpointVelocity = (viewpoint - _prevViewpoint) / Math.Max(dt, 0.001f);
            _prevViewpoint = viewpoint;

            // 快速更新：每帧触发（优先级刷新 + 可见性更新 + HLOD 判定）
            _fastUpdateTimer += dt;
            if (_fastUpdateTimer >= 0.033f) // ~30Hz
            {
                _fastUpdateTimer = 0f;
                UpdateVisibilityAndHlod();
                UpdatePriorityScores();
            }

            // 完整流送更新：周期性触发（100ms）
            _updateTimer += dt;
            if (_updateTimer < 0.1f) return;
            _updateTimer = 0f;

            // 1. 更新数据层状态
            if (_options.EnableDataLayers)
                UpdateDataLayers(viewpoint);

            // 2. 更新子关卡状态
            UpdateSubLevels(viewpoint);

            // 3. 扫描流送需求，生成加载/卸载请求
            ScanStreamingNeeds(viewpoint);

            // 4. 预测加载（基于速度方向）
            if (_options.EnablePredictiveLoading)
                ScanPredictiveNeeds(dt, viewpoint);

            // 5. 启动新的后台加载作业（受并发上限）
            StartPendingLoads();

            // 6. 处理已完成的加载作业（受帧预算限制）
            ProcessCompletedLoads();

            // 7. 处理卸载队列
            ProcessUnloadQueue();

            // 8. 内存预算检查与 LRU 淘汰
            ProcessMemoryEviction();
        }

        // ── 流送需求扫描 ────────────────────────────────────────────────

        /// <summary>
        /// 扫描视点周围，确定哪些 Cell 需要加载、哪些需要卸载。
        /// 考虑数据层状态、加载范围、迟滞卸载。
        /// </summary>
        private void ScanStreamingNeeds(Vector3 viewpoint)
        {
            int range = _options.LoadRadius;
            int unloadRange = _options.UnloadRadius + _options.UnloadHysteresis;
            int vx = (int)MathF.Floor(viewpoint.X / _options.CellSize);
            int vy = (int)MathF.Floor(viewpoint.Y / _options.CellSize);
            int vz = (int)MathF.Floor(viewpoint.Z / _options.CellSize);

            // 收集需要加载的候选
            var loadCandidates = new List<(int x, int y, int z, float dist)>();
            for (int x = vx - range; x <= vx + range; x++)
                for (int y = vy - range; y <= vy + range; y++)
                    for (int z = vz - range; z <= vz + range; z++)
                    {
                        float dist = Math.Max(
                            Math.Max(Math.Abs(x - vx), Math.Abs(y - vy)),
                            Math.Abs(z - vz));
                        if (dist <= range)
                            loadCandidates.Add((x, y, z, dist));
                    }

            loadCandidates.Sort((a, b) => a.dist.CompareTo(b.dist));

            // 为候选 Cell 生成加载请求
            foreach (var info in loadCandidates)
            {
                var cell = GetOrCreateCell(info.x, info.y, info.z);

                // 检查数据层是否允许加载
                if (!IsCellDataLayerActive(cell)) continue;

                if (cell.State == CellState.Unloaded || cell.State == CellState.Unloading)
                {
                    EnqueueLoadRequest(cell, CalculatePriority(cell, viewpoint));
                }
            }

            // 检查超出卸载半径的活跃 Cell
            var toUnload = new List<WorldCell>();
            foreach (var cell in _activeCells)
            {
                if (cell.IsPersistent || cell.IsAlwaysLoaded) continue;
                if (cell.ReferenceCount > 0) continue;

                int dx = Math.Abs(cell.GridX - vx);
                int dy = Math.Abs(cell.GridY - vy);
                int dz = Math.Abs(cell.GridZ - vz);
                int gridDist = Math.Max(Math.Max(dx, dy), dz);

                if (gridDist > unloadRange)
                    toUnload.Add(cell);
            }

            foreach (var cell in toUnload)
                EnqueueUnloadRequest(cell);
        }

        /// <summary>
        /// 预测加载：基于视点移动速度和方向，预加载玩家即将到达的区域。
        /// </summary>
        private void ScanPredictiveNeeds(float dt, Vector3 viewpoint)
        {
            float speed = _viewpointVelocity.Length();
            if (speed < 1f) return; // 速度太低不预测

            Vector3 predictPos = viewpoint + _viewpointVelocity * _options.PredictiveLookAheadSeconds;
            int pvx = (int)MathF.Floor(predictPos.X / _options.CellSize);
            int pvy = (int)MathF.Floor(predictPos.Y / _options.CellSize);
            int pvz = (int)MathF.Floor(predictPos.Z / _options.CellSize);

            int vx = (int)MathF.Floor(viewpoint.X / _options.CellSize);
            int vy = (int)MathF.Floor(viewpoint.Y / _options.CellSize);
            int vz = (int)MathF.Floor(viewpoint.Z / _options.CellSize);

            int predRange = 2; // 预测区域较小
            for (int x = pvx - predRange; x <= pvx + predRange; x++)
                for (int y = pvy - predRange; y <= pvy + predRange; y++)
                    for (int z = pvz - predRange; z <= pvz + predRange; z++)
                    {
                        // 只预加载当前加载范围外的 Cell
                        int dx = Math.Abs(x - vx);
                        int dy = Math.Abs(y - vy);
                        int dz = Math.Abs(z - vz);
                        int gridDist = Math.Max(Math.Max(dx, dy), dz);
                        if (gridDist <= _options.LoadRadius) continue;

                        var cell = GetOrCreateCell(x, y, z);
                        if (cell.State != CellState.Unloaded) continue;
                        if (!IsCellDataLayerActive(cell)) continue;

                        // 预测加载给稍低的优先级
                        float priority = CalculatePriority(cell, predictPos) * 0.5f;
                        EnqueueLoadRequest(cell, priority);
                    }
        }

        // ── 数据层更新 ────────────────────────────────────────────────

        /// <summary>
        /// 更新所有数据层的状态。根据加载策略决定各层是否应加载/卸载。
        /// </summary>
        private void UpdateDataLayers(Vector3 viewpoint)
        {
            foreach (var layer in _dataLayers.Values)
            {
                switch (layer.Strategy)
                {
                    case DataLayerLoadingStrategy.AlwaysLoaded:
                        if (!layer.IsLoaded) layer.SetLoaded(true);
                        break;

                    case DataLayerLoadingStrategy.DistanceBased:
                        bool shouldLoad = false;
                        foreach (var cellId in layer.CellIds)
                        {
                            if (_cells.TryGetValue(cellId, out var cell))
                            {
                                float dist = Vector3.Distance(cell.Center, viewpoint);
                                if (dist <= layer.LoadRadius) { shouldLoad = true; break; }
                            }
                        }
                        if (shouldLoad && !layer.IsLoaded)
                            layer.SetLoaded(true);
                        else if (!shouldLoad && layer.IsLoaded)
                        {
                            // 检查所有 Cell 是否都超出卸载半径
                            bool allFar = true;
                            foreach (var cellId in layer.CellIds)
                            {
                                if (_cells.TryGetValue(cellId, out var cell))
                                {
                                    float dist = Vector3.Distance(cell.Center, viewpoint);
                                    if (dist <= layer.UnloadRadius) { allFar = false; break; }
                                }
                            }
                            if (allFar) layer.SetLoaded(false);
                        }
                        break;

                    case DataLayerLoadingStrategy.VolumeTriggered:
                        // 由外部手动控制或流送体积触发
                        break;

                    case DataLayerLoadingStrategy.Manual:
                        // 由代码显式控制
                        break;
                }
            }
        }

        /// <summary>检查 Cell 的所有数据层是否都处于激活状态。</summary>
        private bool IsCellDataLayerActive(WorldCell cell)
        {
            if (cell.DataLayerIds.Count == 0) return true;
            foreach (var layerId in cell.DataLayerIds)
            {
                if (_dataLayers.TryGetValue(layerId, out var layer) && !layer.IsLoaded)
                    return false;
            }
            return true;
        }

        // ── 子关卡更新 ────────────────────────────────────────────────

        /// <summary>
        /// 更新子关卡状态。根据子关卡边界与视点距离决定加载/卸载。
        /// </summary>
        private void UpdateSubLevels(Vector3 viewpoint)
        {
            foreach (var subLevel in _subLevels.Values)
            {
                if (subLevel.IsPersistent)
                {
                    if (subLevel.State == SubLevelState.Unloaded)
                        LoadSubLevel(subLevel);
                    continue;
                }

                float dist = subLevel.Bounds.DistanceTo(viewpoint);
                float loadDist = _options.CellSize * _options.LoadRadius;
                float unloadDist = _options.CellSize * (_options.UnloadRadius + _options.UnloadHysteresis);

                if (subLevel.State == SubLevelState.Unloaded && dist <= loadDist)
                {
                    LoadSubLevel(subLevel);
                }
                else if (subLevel.State == SubLevelState.Loaded && dist > unloadDist)
                {
                    UnloadSubLevel(subLevel);
                }

                // 更新优先级
                subLevel.Priority = 1f / (1f + dist * 0.001f);
            }
        }

        /// <summary>加载子关卡（将其内所有 Cell 标记为可加载）。</summary>
        private void LoadSubLevel(SubLevelData subLevel)
        {
            subLevel.State = SubLevelState.Loading;
            Log($"加载子关卡: {subLevel.Name}");

            foreach (var cellId in subLevel.CellIds)
            {
                if (_cells.TryGetValue(cellId, out var cell) &&
                    cell.State == CellState.Unloaded)
                {
                    EnqueueLoadRequest(cell, subLevel.Priority);
                }
            }

            subLevel.NotifyLoaded();
            OnSubLevelLoaded?.Invoke(subLevel);
        }

        /// <summary>卸载子关卡（卸载其内所有非持久 Cell）。</summary>
        private void UnloadSubLevel(SubLevelData subLevel)
        {
            subLevel.State = SubLevelState.Unloading;
            Log($"卸载子关卡: {subLevel.Name}");

            foreach (var cellId in subLevel.CellIds)
            {
                if (_cells.TryGetValue(cellId, out var cell) &&
                    !cell.IsPersistent && cell.ReferenceCount == 0 &&
                    (cell.State == CellState.Loaded || cell.State == CellState.Active))
                {
                    EnqueueUnloadRequest(cell);
                }
            }

            subLevel.NotifyUnloaded();
            OnSubLevelUnloaded?.Invoke(subLevel);
        }

        // ── 可见性与 HLOD 更新（高频，~30Hz） ─────────────────────────

        /// <summary>
        /// 更新活跃 Cell 的视锥可见性（带迟滞）和 HLOD 状态。
        /// </summary>
        private void UpdateVisibilityAndHlod()
        {
            bool hasValidFrustum = _viewProjection != Matrix4x4.Identity;

            Span<Vector4> planes = stackalloc Vector4[6];
            if (hasValidFrustum)
                ExtractFrustumPlanes(_viewProjection, planes);

            foreach (var cell in _activeCells)
            {
                // 视锥可见性测试（带迟滞）
                cell.WasFrustumVisible = cell.IsFrustumVisible;
                cell.IsFrustumVisible = hasValidFrustum
                    ? IntersectsFrustum(cell.Bounds, planes)
                    : true;

                // 迟滞：必须连续 N 帧不可见才判定为不可见
                if (!cell.IsFrustumVisible && cell.WasFrustumVisible)
                    cell.IsFrustumVisible = true; // 保持上一帧状态

                // HLOD 判定
                if (_options.EnableHlod && cell.HlodAssetId.HasValue)
                {
                    float dist = Vector3.Distance(cell.Center, _viewpoint);
                    bool shouldUseHlod = dist > cell.HlodSwitchDistance;
                    if (shouldUseHlod != cell.IsUsingHlod)
                    {
                        cell.IsUsingHlod = shouldUseHlod;
                        OnHlodSwitch?.Invoke(cell, shouldUseHlod);
                    }
                }
            }
        }

        // ── 优先级计算 ────────────────────────────────────────────────

        /// <summary>
        /// 计算综合优先级得分。
        /// 公式：DistanceScore x VisibilityWeight + LayerWeight x DataLayerWeight + ImportanceWeight
        /// </summary>
        private void UpdatePriorityScores()
        {
            foreach (var cell in _activeCells)
            {
                cell.PriorityScore = CalculatePriority(cell, _viewpoint);
            }
        }

        private float CalculatePriority(WorldCell cell, Vector3 viewpoint)
        {
            float dist = Vector3.Distance(cell.Center, viewpoint);
            float distScore = 1f / (1f + dist * 0.001f);

            // 可见性得分：可见=1.0, 不可见=0.2
            float visScore = cell.IsFrustumVisible ? 1f : 0.2f;

            // 数据层权重加成
            float layerWeight = 1f;
            foreach (var layerId in cell.DataLayerIds)
            {
                if (_dataLayers.TryGetValue(layerId, out var layer))
                    layerWeight = Math.Max(layerWeight, layer.PriorityWeight);
            }

            // 综合优先级
            float priority = distScore * _options.DistanceWeight +
                             visScore * _options.VisibilityWeight +
                             cell.ImportanceWeight * _options.ImportanceWeight +
                             layerWeight * 0.1f;

            return priority;
        }

        // ── 加载请求队列 ────────────────────────────────────────────

        private void EnqueueLoadRequest(WorldCell cell, float priority)
        {
            lock (_stateLock)
            {
                // 已在队列或正在加载则跳过
                if (cell.State == CellState.Loading || cell.State == CellState.Loaded || cell.State == CellState.Active)
                    return;
                if (_loadRequestQueue.Any(r => r.CellId == cell.Id)) return;
                if (_activeJobs.Any(j => j.CellId == cell.Id)) return;

                cell.State = CellState.Loading;
                cell.LoadProgress = 0f;
                _loadingCells.Add(cell);

                // 插入到已排序列表中（保持有序）
                var request = new PartitionLoadRequest
                {
                    CellId = cell.Id,
                    Priority = priority,
                    RequestTime = DateTime.Now,
                    IsUnload = false,
                    TargetLod = cell.TargetLodLevel
                };

                int insertIdx = _loadRequestQueue.BinarySearch(request);
                if (insertIdx < 0) insertIdx = ~insertIdx;
                _loadRequestQueue.Insert(insertIdx, request);
            }
        }

        private void EnqueueUnloadRequest(WorldCell cell)
        {
            lock (_stateLock)
            {
                if (cell.State == CellState.Unloaded || cell.State == CellState.Unloading)
                    return;

                // 若正在加载，取消请求
                _loadRequestQueue.RemoveAll(r => r.CellId == cell.Id);

                cell.State = CellState.Unloading;
                _unloadQueue.Enqueue(cell);
            }
        }

        // ── 后台加载作业 ────────────────────────────────────────────

        private void StartPendingLoads()
        {
            lock (_stateLock)
            {
                while (_loadRequestQueue.Count > 0 &&
                       _activeJobs.Count < _options.MaxConcurrentLoads)
                {
                    var request = _loadRequestQueue[0];
                    _loadRequestQueue.RemoveAt(0);

                    if (!_cells.TryGetValue(request.CellId, out var cell)) continue;
                    if (cell.State != CellState.Loading) continue;

                    var job = new PartitionLoadJob
                    {
                        CellId = cell.Id,
                        TargetLod = request.TargetLod
                    };

                    cell.LoadCts = new CancellationTokenSource();

                    var cellRef = cell; // 闭包捕获
                    var cts = cell.LoadCts;
                    var shutdownToken = _shutdownCts.Token;

                    job.Task = Task.Run(() =>
                    {
                        try
                        {
                            var linkedCts = CancellationTokenSource.CreateLinkedTokenSource(
                                cts.Token, shutdownToken);
                            var token = linkedCts.Token;

                            // 模拟后台磁盘 I/O
                            // 实际实现: AssetDatabase.LoadAssetsAsync(cell.AssetIds)
                            if (token.WaitHandle.WaitOne(10)) // 模拟 I/O
                            {
                                job.IsCancelled = true;
                                return;
                            }

                            job.LoadedBytes = cellRef.MemoryFootprintKB;
                            linkedCts.Dispose();
                        }
                        catch (OperationCanceledException)
                        {
                            job.IsCancelled = true;
                        }
                        catch (Exception ex)
                        {
                            job.Error = ex;
                        }
                    }, cts.Token);

                    _activeJobs.Add(job);
                }
            }
        }

        // ── 处理已完成加载 ────────────────────────────────────────────

        private void ProcessCompletedLoads()
        {
            List<PartitionLoadJob> done;
            lock (_stateLock)
            {
                done = new List<PartitionLoadJob>();
                for (int i = _activeJobs.Count - 1; i >= 0; i--)
                {
                    if (_activeJobs[i].Task.IsCompleted)
                    {
                        done.Add(_activeJobs[i]);
                        _activeJobs.RemoveAt(i);
                    }
                }
            }

            foreach (var job in done)
            {
                if (!_cells.TryGetValue(job.CellId, out var cell)) continue;

                // 释放信号量
                _workerSemaphore.Release();

                if (job.IsCancelled || job.Error != null)
                {
                    cell.State = CellState.Unloaded;
                    cell.LoadProgress = 0f;
                    cell.LoadCts?.Dispose();
                    cell.LoadCts = null;
                    _loadingCells.Remove(cell);

                    if (job.Error != null)
                        Log($"Cell 加载失败 [{cell.GridX},{cell.GridY},{cell.GridZ}]: {job.ErrorMessage}");
                    continue;
                }

                // Cell 已被请求卸载 -> 丢弃加载结果
                if (cell.State == CellState.Unloading)
                {
                    cell.State = CellState.Unloaded;
                    cell.LoadProgress = 0f;
                    cell.LoadCts?.Dispose();
                    cell.LoadCts = null;
                    _loadingCells.Remove(cell);
                    EnqueueUnloadRequest(cell);
                    continue;
                }

                // 完成加载
                cell.State = CellState.Loaded;
                cell.LoadProgress = 1f;
                cell.LastAccessTime = DateTime.Now;
                cell.LoadCts?.Dispose();
                cell.LoadCts = null;
                _loadingCells.Remove(cell);

                if (!_activeCells.Contains(cell))
                    _activeCells.Add(cell);

                _currentMemoryKB += cell.MemoryFootprintKB;

                OnCellLoaded?.Invoke(cell);

                // 自动激活近距离 Cell
                float dist = Vector3.Distance(cell.Center, _viewpoint);
                if (dist <= _options.CellSize * 2f)
                {
                    cell.State = CellState.Active;
                    OnCellActivated?.Invoke(cell);
                }

                // 内存压力检查
                if (MemoryUsageRatio > 0.85f)
                    OnMemoryPressure?.Invoke(MemoryUsageRatio);
            }
        }

        // ── 处理卸载队列 ────────────────────────────────────────────

        private void ProcessUnloadQueue()
        {
            int processed = 0;
            int maxPerUpdate = 4; // 每次最多处理 4 个卸载

            while (_unloadQueue.Count > 0 && processed < maxPerUpdate)
            {
                var cell = _unloadQueue.Dequeue();
                processed++;

                // 取消加载
                cell.LoadCts?.Cancel();
                cell.LoadCts?.Dispose();
                cell.LoadCts = null;

                // 释放内存
                _currentMemoryKB = Math.Max(0, _currentMemoryKB - cell.MemoryFootprintKB);

                // 重置状态
                cell.State = CellState.Unloaded;
                cell.LoadProgress = 0f;
                cell.IsUsingHlod = false;
                cell.IsFrustumVisible = false;
                cell.WasFrustumVisible = false;

                _activeCells.Remove(cell);
                _loadingCells.Remove(cell);

                OnCellUnloaded?.Invoke(cell);
            }
        }

        // ── 内存预算与 LRU 淘汰 ─────────────────────────────────────

        private void ProcessMemoryEviction()
        {
            if (_currentMemoryKB <= _options.MemoryBudgetKB) return;

            // 计算需要释放的内存量
            long targetEvict = (long)((_currentMemoryKB - _options.MemoryBudgetKB * 0.8f) +
                                       _options.MemoryBudgetKB * 0.15f);

            // 按 LastAccessTime 排序（最久未使用优先淘汰）
            var candidates = _activeCells
                .Where(c => !c.IsPersistent && !c.IsAlwaysLoaded && c.ReferenceCount == 0)
                .OrderBy(c => c.LastAccessTime)
                .ToList();

            long evicted = 0;
            foreach (var cell in candidates)
            {
                if (evicted >= targetEvict) break;
                EnqueueUnloadRequest(cell);
                evicted += cell.MemoryFootprintKB;
            }

            if (evicted > 0)
                Log($"内存淘汰: 释放 {evicted}KB ({candidates.Count} 个 Cell)");
        }

