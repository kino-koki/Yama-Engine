        /// <summary>
        /// 获取或创建指定网格坐标的 Cell。
        /// </summary>
        public WorldCell GetOrCreateCell(int x, int y, int z)
        {
            var key = (x, y, z);
            if (_gridLookup.TryGetValue(key, out var existing)) return existing;

            var cell = new WorldCell
            {
                GridX = x,
                GridY = y,
                GridZ = z,
                Id = Guid.NewGuid(),
                Center = new Vector3(x * _options.CellSize + _options.CellSize * 0.5f,
                                       y * _options.CellSize + _options.CellSize * 0.5f,
                                       z * _options.CellSize + _options.CellSize * 0.5f),
                Size = _options.CellSize,
                State = CellState.Unloaded,
                Name = $"Cell_{x}_{y}_{z}",
                LastAccessTime = DateTime.Now,
                IsPersistent = false,
                IsAlwaysLoaded = false,
                HlodSwitchDistance = _options.HlodDefaultSwitchDistance
            };
            _cells[cell.Id] = cell;
            _gridLookup[key] = cell;
            _currentLevel?.Cells.Add(cell);
            return cell;
        }

        /// <summary>
