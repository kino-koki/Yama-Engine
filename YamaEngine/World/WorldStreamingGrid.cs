    /// <summary>
    /// UE6 级世界分区系统。核心职责：
    /// 1. 数据图层 (DataLayer) 管理：按需加载/卸载逻辑数据分层
    /// 2. 分区网格 (PartitionGrid)：空间哈希网格划分与 Cell 管理
    /// 3. 加载范围 (LoadingRange)：基于距离的流送控制 + 迟滞卸载
    /// 4. 分区优先级：距离 x 可见性 x 重要性 x 数据层权重的综合评分
    /// 5. 异步加载队列：优先级队列驱动的后台加载 + 帧预算限制
    /// 6. 分区状态机：Unloaded -> Loading -> Loaded -> Active -> Unloading -> Unloaded
    /// 7. 关卡流送：子关卡 (SubLevel) 动态加载/卸载
    /// 8. HLOD 系统：分区级 Hierarchical LOD 管理 + 自动合并
    /// </summary>
    public class WorldStreamingGridSystem
    {
        // ── 内部数据结构 ──

        /// <summary>所有 Cell 字典（按 Guid 索引）。</summary>
        private readonly Dictionary<Guid, WorldCell> _cells = new();

        /// <summary>网格坐标 -> Cell 映射。</summary>
        private readonly Dictionary<(int, int, int), WorldCell> _gridLookup = new();

        /// <summary>当前活跃（已加载/已激活）的 Cell 列表。</summary>
        private readonly List<WorldCell> _activeCells = new();

        /// <summary>正在加载中的 Cell 列表。</summary>
        private readonly List<WorldCell> _loadingCells = new();

        /// <summary>等待卸载的 Cell 队列。</summary>
        private readonly Queue<WorldCell> _unloadQueue = new();

        /// <summary>加载请求优先级队列（已排序列表，Insert 保持有序）。</summary>
        private readonly List<PartitionLoadRequest> _loadRequestQueue = new();

        /// <summary>卸载请求优先级队列。</summary>
        private readonly List<PartitionLoadRequest> _unloadRequestQueue = new();

        /// <summary>活跃的后台加载作业列表。</summary>
        private readonly List<PartitionLoadJob> _activeJobs = new();

        /// <summary>已完成等待主线程处理的作业列表。</summary>
        private readonly Queue<PartitionLoadJob> _completedJobs = new();

        /// <summary>所有注册的关卡数据。</summary>
        private readonly Dictionary<Guid, LevelData> _levels = new();

        /// <summary>当前活跃关卡。</summary>
        private LevelData? _currentLevel;

        /// <summary>所有数据层。</summary>
        private readonly Dictionary<Guid, DataLayer> _dataLayers = new();

        /// <summary>所有子关卡。</summary>
        private readonly Dictionary<Guid, SubLevelData> _subLevels = new();

        /// <summary>所有 HLOD 集群。</summary>
        private readonly Dictionary<Guid, HlodCluster> _hlodClusters = new();

        /// <summary>Cell -> HLOD 集群映射。</summary>
        private readonly Dictionary<Guid, Guid> _cellHlodMapping = new();

        /// <summary>流送配置。</summary>
        private StreamingOptions _options = StreamingOptions.Default;

        /// <summary>当前视点位置。</summary>
        private Vector3 _viewpoint;

        /// <summary>视点移动速度（用于预测加载）。</summary>
        private Vector3 _viewpointVelocity;

        /// <summary>上一帧视点位置。</summary>
        private Vector3 _prevViewpoint;

        /// <summary>视锥投影矩阵。</summary>
        private Matrix4x4 _viewProjection = Matrix4x4.Identity;

        /// <summary>更新计时器。</summary>
        private float _updateTimer;

        /// <summary>轻量更新计时器（每帧触发优先级刷新）。</summary>
        private float _fastUpdateTimer;

        /// <summary>实体位置注册表。</summary>
        private readonly Dictionary<int, Vector3> _entityPositions = new();

        /// <summary>当前内存使用量（KB）。</summary>
        private long _currentMemoryKB;

        /// <summary>后台加载线程信号量。</summary>
        private readonly SemaphoreSlim _workerSemaphore;

        /// <summary>系统关闭令牌。</summary>
        private CancellationTokenSource _shutdownCts = new();

        /// <summary>锁对象（保护共享状态）。</summary>
        private readonly object _stateLock = new();

        // ── 公共属性（保持原有 API） ──

        public int TotalCellCount => _cells.Count;
        public int ActiveCellCount => _activeCells.Count;
