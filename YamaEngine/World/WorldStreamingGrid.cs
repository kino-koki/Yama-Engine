        public void ClearAll()
        {
            _shutdownCts.Cancel();

            foreach (var cell in _loadingCells.ToList())
            {
                cell.LoadCts?.Cancel();
                cell.LoadCts?.Dispose();
                cell.State = CellState.Unloaded;
            }

            _cells.Clear();
            _gridLookup.Clear();
            _activeCells.Clear();
            _loadingCells.Clear();
            _unloadQueue.Clear();
            _loadRequestQueue.Clear();
            _unloadRequestQueue.Clear();
            _activeJobs.Clear();
            _completedJobs.Clear();
            _entityPositions.Clear();
            _dataLayers.Clear();
            _subLevels.Clear();
            _hlodClusters.Clear();
            _cellHlodMapping.Clear();
            _currentMemoryKB = 0;
            _currentLevel?.Cells.Clear();

            _shutdownCts.Dispose();
            _shutdownCts = new CancellationTokenSource();

            Log("World partition cleared");
        }

