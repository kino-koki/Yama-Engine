    /// <summary>
    /// 分区单元状态机。
    /// Unloaded → Loading → Loaded → Active → Unloading → Unloaded
    /// </summary>
    public enum CellState
    {
        /// <summary>已卸载：数据不在内存中。</summary>
        Unloaded,
        /// <summary>加载中：后台线程正在读取资产。</summary>
        Loading,
        /// <summary>已加载：资产就绪但未激活（预流送）。</summary>
        Loaded,
        /// <summary>已激活：已加载并参与游戏逻辑/渲染。</summary>
        Active,
        /// <summary>卸载中：正在释放资源。</summary>
        Unloading
    }

    /// <summary>
    /// 数据层加载策略：决定数据层在运行时如何加载。
    /// </summary>
    public enum DataLayerLoadingStrategy
    {
        /// <summary>始终加载：常驻内存，不自动卸载。</summary>
        AlwaysLoaded,
        /// <summary>按距离加载：进入加载半径加载，离开卸载半径卸载。</summary>
        DistanceBased,
        /// <summary>按流送体积加载：进入触发体积时加载。</summary>
        VolumeTriggered,
        /// <summary>手动控制：由代码显式调用。</summary>
        Manual
    }

    /// <summary>
    /// HLOD 模型来源类型。
    /// </summary>
    public enum HlodSourceMode
    {
        /// <summary>自动生成：由 HLOD 生成器根据原始网格合并简化。</summary>
        AutoGenerated,
        /// <summary>手动指定：由美术人员手动提供 HLOD 网格。</summary>
        ManualOverride,
        /// <summary>无 HLOD：此分区不使用 HLOD。</summary>
        None
    }

    /// <summary>
    /// 子关卡加载状态。
